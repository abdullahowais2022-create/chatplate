const DICTS: Record<string, Dict> = { en, ar, fr, es, hi, ur, tr };
export const BUILTIN_LANGUAGES = Object.keys(DICTS);

/** Extra dictionaries supplied at runtime (e.g. machine-translated labels for other languages). */
const runtime = new Map<string, Partial<Dict>>();
export function registerLanguage(lang: string, dict: Partial<Dict>) {
  runtime.set(lang, dict);
}

export function baseLang(lang: string | null | undefined): string {
  return (lang ?? "en").toLowerCase().split(/[-_]/)[0] || "en";
}

export function hasBuiltin(lang: string | null | undefined) {
  return baseLang(lang) in DICTS;
}

export function t(lang: string | null | undefined, key: I18nKey, vars: Record<string, string | number> = {}): string {
  const l = baseLang(lang);
  const template = DICTS[l]?.[key] ?? runtime.get(l)?.[key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

